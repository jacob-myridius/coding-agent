/**
 * Handles the ai:ready-for-implementation-plan route for ADO work items.
 *
 * Guards on test-plan-*.md attachment existing before generating.
 * Follows the same pattern as implementation-plan-handler.js (Jira/GitHub paths).
 */

import { readFile } from "node:fs/promises";
import path from "node:path";

/**
 * Handle implementation plan generation for an ADO work item.
 * Guards on test-plan-*.md attachment existing before generating.
 *
 * @param {number|string} workItemId
 * @param {object} azdo - AzdoClient instance
 * @param {object} agentCtx - _agentContext from payload
 * @param {string[]} registeredRepos - list of registered repo names/slugs
 */
export async function handleAdoImplementationPlan(workItemId, azdo, agentCtx, registeredRepos) {
  const projectId = agentCtx?.projectId;
  const executionId = agentCtx?.executionId ?? "unknown";
  const consoleUrl = process.env.CONSOLE_URL;
  const callbackSecret = process.env.AGENT_CALLBACK_SECRET;

  console.log("[ado-impl-plan] starting plan generation", { workItemId, projectId, executionId });

  // 1. Fetch work item fields
  const workItem = await azdo.getWorkItem(workItemId);
  const fields = workItem.fields ?? {};
  const title = String(fields["System.Title"] ?? "").trim();
  const description = String(fields["System.Description"] ?? "").trim();
  const acceptanceCriteria = String(fields["Microsoft.VSTS.Common.AcceptanceCriteria"] ?? "").trim();

  // 2. Check for test-plan-*.md attachment
  const attachments = await azdo.fetchAttachments(workItemId);
  const testPlanAttachment = attachments.find((a) => /^test-plan-.+\.md$/i.test(a.name));
  if (!testPlanAttachment) {
    await azdo.postComment(
      workItemId,
      "⚠️ A test plan is required before the implementation plan can be generated. " +
        "Please apply `ai:ready-for-test-plan` to generate it first."
    );
    await azdo.updateTags(workItemId, ["ai:ready-for-implementation-plan"], ["ai:needs-test-plan"]);
    console.log(`[ado-impl-plan] Blocked: no test-plan attachment for work item ${workItemId}`);
    return { status: "blocked", reason: "MissingTestPlan" };
  }

  // 3. Download test plan + architecture/UX docs from linked work items
  const testPlanContent = await azdo.downloadAttachment(testPlanAttachment.url);
  let archDoc = "";
  let uiuxDoc = "";
  try {
    const linked = await azdo.fetchLinkedWorkItems(workItemId);
    for (const link of linked) {
      const linkedAttachments = await azdo.fetchAttachments(link.id);
      for (const att of linkedAttachments) {
        if (/^system-design-.+\.md$/i.test(att.name) && !archDoc) {
          archDoc = await azdo.downloadAttachment(att.url).catch(() => "");
        }
        if (/^uiux-spec-.+\.md$/i.test(att.name) && !uiuxDoc) {
          uiuxDoc = await azdo.downloadAttachment(att.url).catch(() => "");
        }
      }
      if (archDoc && uiuxDoc) break;
    }
  } catch (e) {
    console.warn("[ado-impl-plan] Could not fetch linked work items:", e.message);
  }

  // 4. Load prompt template and build prompt
  const promptTemplate = await readFile(
    path.join(process.cwd(), "prompts", "implementation-plan-prompt.md"),
    "utf8"
  );
  const reposText =
    (registeredRepos ?? []).map((r) => `- ${r.name ?? r}`).join("\n") || "N/A";

  const prompt = promptTemplate
    .replaceAll("{{ISSUE_KEY}}", String(workItemId))
    .replaceAll("{{TITLE}}", title)
    .replaceAll("{{DESCRIPTION}}", description || "(no description)")
    .replaceAll("{{ACCEPTANCE_CRITERIA}}", acceptanceCriteria || "(no acceptance criteria)")
    .replaceAll("{{ARCHITECTURE_DOC}}", archDoc || "Not provided")
    .replaceAll("{{UIUX_DOC}}", uiuxDoc || "Not provided")
    .replaceAll("{{TEST_PLAN}}", testPlanContent || "Not provided")
    .replaceAll("{{REGISTERED_REPOS}}", reposText);

  // 5. Call Azure OpenAI
  const { content: planContent, usage: tokenUsage } = await callAzureOpenAI(prompt);

  // 6. Upload plan as attachment
  const fileName = `implementation-plan-${executionId}.md`;
  await azdo.uploadAttachment(workItemId, fileName, planContent);

  // 7. Post comment
  await azdo.postComment(
    workItemId,
    `## Implementation Plan Generated\n\n` +
      `An implementation plan has been attached as \`${fileName}\`.\n\n` +
      "Review it and apply `ai:ready-for-implementation` when ready.\n\n" +
      `*Generated by Myridius Code Agent · Execution ${executionId}*`
  );

  // 8. Update tags
  await azdo.updateTags(workItemId, ["ai:ready-for-implementation-plan"], ["ai:implementation-plan-proposed"]);

  // 9. Emit console event
  if (consoleUrl && callbackSecret && projectId) {
    logConsoleEvent(consoleUrl, callbackSecret, projectId, {
      stage: "implementation",
      agentName: "code",
      eventType: "plan-generated",
      summary: `Implementation plan generated for ADO #${workItemId}`,
      storyId: String(workItemId),
      detail: JSON.stringify({ executionId }),
      tokenUsage,
    });
  }

  console.log("[ado-impl-plan] plan generated and attached", { workItemId, fileName });
  return { status: "plan-generated", workItemId, fileName };
}


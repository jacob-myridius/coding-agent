async function callAzureOpenAI(prompt) {
  const endpoint = (process.env.AZURE_OPENAI_ENDPOINT || "").replace(/\/$/, "");
  const apiKey = process.env.AZURE_OPENAI_API_KEY;
  const deployment = process.env.AZURE_OPENAI_DEPLOYMENT;
  const apiVersion = process.env.AZURE_OPENAI_API_VERSION ?? "2024-02-01";

  if (!endpoint || !apiKey || !deployment) {
    throw new Error(
      "[ado-impl-plan] AZURE_OPENAI_ENDPOINT, AZURE_OPENAI_API_KEY, and AZURE_OPENAI_DEPLOYMENT must be set"
    );
  }

  const url = `${endpoint}/openai/deployments/${deployment}/chat/completions?api-version=${apiVersion}`;
  const MAX_RETRIES = 3;
  const BASE_BACKOFF_MS = 2000;

  let lastError;
  for (let attempt = 0; attempt <= MAX_RETRIES; attempt++) {
    const res = await fetch(url, {
      method: "POST",
      headers: { "Content-Type": "application/json", "api-key": apiKey },
      body: JSON.stringify({
        messages: [
          {
            role: "system",
            content:
              "You are a senior software engineer who writes detailed, actionable implementation plans.",
          },
          { role: "user", content: prompt },
        ],
        max_completion_tokens: 8000,
        temperature: 0.3,
      }),
    });

    if (res.status === 429) {
      const retryAfterSec = Number(res.headers.get("Retry-After") ?? 0);
      const waitMs =
        retryAfterSec > 0 ? retryAfterSec * 1000 : BASE_BACKOFF_MS * Math.pow(2, attempt);
      lastError = new Error(
        `Azure OpenAI rate limited (429) — retry ${attempt + 1}/${MAX_RETRIES}`
      );
      console.warn("[ado-impl-plan] rate limited", { attempt, waitMs });
      if (attempt < MAX_RETRIES) {
        await new Promise((resolve) => setTimeout(resolve, waitMs));
        continue;
      }
      break;
    }

    if (!res.ok) {
      const text = await res.text().catch(() => "");
      throw new Error(`[ado-impl-plan] Azure OpenAI request failed (${res.status}): ${text}`);
    }

    const data = await res.json();
    const content = data.choices?.[0]?.message?.content;
    if (!content) throw new Error("[ado-impl-plan] Azure OpenAI returned empty response");
    const u = data.usage;
    return {
      content,
      usage: u
        ? {
            promptTokens: u.prompt_tokens,
            completionTokens: u.completion_tokens,
            totalTokens: u.total_tokens,
          }
        : undefined,
    };
  }

  throw lastError ?? new Error("[ado-impl-plan] Azure OpenAI request failed after retries");
}

function logConsoleEvent(consoleUrl, secret, projectId, event) {
  fetch(`${consoleUrl}/api/projects/${projectId}/events`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${secret}`,
    },
    body: JSON.stringify(event),
  }).catch((e) => {
    console.error("[ado-impl-plan] Console event failed:", e.message);
  });
}
